"""Generate executable help lines from the checked mapping catalog; never sends commands."""
from pathlib import Path
import json,sys
H=Path(__file__).resolve().parents[1]
groups=json.loads((H/'Docs/输入映射/指令帮助目录.json').read_text(encoding='utf-8'))
lines=['/* Generated by Tools/generate_console_help.py; edit the JSON catalog. */','#ifndef CONSOLE_HELP_H','#define CONSOLE_HELP_H',f'#define CONSOLE_HELP_COUNT {len(groups)}U','static const char *const help_names[]={'+','.join(json.dumps(g['label']) for g in groups)+'};']
for g in groups:
 a=['# '+g['label']+'; copy ONE command line; edit numeric values as needed.']
 for x in g['items']:a+=['# '+x['note'],x['example']]
 assert all(len(t.encode('utf-8'))<180 for t in a)
 lines+=['static const char *const help_'+str(g['id'])+'[]={'+','.join(json.dumps(t) for t in a)+',0};']
lines+=['static const char *const *const help_text[]={'+','.join('help_'+str(g['id']) for g in groups)+'};','#endif']
target=H/'project/App/modules/integration/console_help.h';expected='\n'.join(lines)+'\n'
if '--check' in sys.argv:assert target.read_text(encoding='utf-8')==expected,'generated help differs from JSON'
elif not target.exists() or target.read_text(encoding='utf-8')!=expected:target.write_text(expected,encoding='utf-8')
print('generated',len(groups),'help groups')
